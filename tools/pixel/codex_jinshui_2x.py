SIZE = (96, 128)
PALETTE = {**COLORS, "hair_shadow": "#49465d", "seam": "#ae3549",
           "sole": "#211c2e", "thread": "#df5960"}


class Sprite:
    def __init__(self):
        self.image = Image.new("RGBA", SIZE)
        self.draw = ImageDraw.Draw(self.image)

    def shape(self, color, points, border=False):
        self.draw.polygon(points, fill=PALETTE[color],
                          outline=PALETTE["ink"] if border else None,
                          width=2 if border else 1)

    def line(self, color, points, width=1):
        self.draw.line(points, fill=PALETTE[color], width=width)

    def button(self, x, y):
        self.shape("hair", [(x, y), (x+2, y), (x+3, y+1), (x+2, y+3),
                            (x, y+3), (x-1, y+2)])
        self.line("white", [(x, y+1), (x+1, y+1)])

    def beads(self, centers, pendant):
        self.line("wood", [*centers, centers[0]], 2)
        self.line("wood", [centers[len(centers)//2], pendant])
        for x, y in [*centers, pendant]:
            self.shape("wood", [(x-1,y-2),(x+1,y-2),(x+2,y-1),(x+2,y+1),
                                (x+1,y+2),(x-1,y+2),(x-2,y+1),(x-2,y-1)])
            self.line("amber", [(x-1,y),(x+1,y)], 2)
            self.line("gold", [(x-1,y-1),(x,y-1)])

    def fist(self, x, y, far=False):
        self.shape("tan" if far else "skin",
                   [(x-7,y-3),(x-4,y-7),(x+3,y-7),(x+7,y-4),(x+8,y+2),
                    (x+5,y+6),(x,y+7),(x-5,y+5),(x-7,y+2)], True)
        self.line("skin" if far else "light", [(x-4,y-3),(x-2,y-4),(x+3,y-4),
                                              (x+5,y-2)], 2)
        self.line("wood" if far else "tan", [(x-4,y+2),(x-1,y),(x+3,y+1),
                                            (x+5,y+2)])
        self.line("wood" if far else "tan", [(x+1,y-2),(x+1,y-1)])


