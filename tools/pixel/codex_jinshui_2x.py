def build():
    OUT.mkdir(exist_ok=True)
    standing, running = stand(), run()
    standing.save(OUT / "codex_jinshui_2x_stand.png")
    running.save(OUT / "codex_jinshui_2x_run.png")

    # Give both native grids the same display size with nearest-neighbor scaling.
    comparison = Image.new("RGB", (424, 582), "#f4f7f7")
    draw = ImageDraw.Draw(comparison)
    font = ImageFont.load_default()
    for x, title in [(20, "48 x 64  /  4x"), (212, "96 x 128  /  2x")]:
        draw.text((x+96, 25), title, font=font, fill="#29233a", anchor="mm")
    rows = [(old_stand(ANIMATIONS["idle"][1][0]), standing, "#dfeef1"),
            (old_run(0), running, "#f4ebdf")]
    for y, (original, redraw, background) in zip((44, 306), rows):
        comparison.paste(background, (20, y, 404, y+256))
        for x, sprite in [(20, original), (212, redraw)]:
            enlarged = sprite.resize((192, 256), Image.Resampling.NEAREST)
            comparison.paste(enlarged, (x, y), enlarged)
    comparison.save(OUT / "codex_2x_compare.png")


if __name__ == "__main__":
    build()
